"""Минимальный шрифт 5x7 для показа громкости ('v 12') и станции ('s 3').

Раньше шрифт давала GyverGFX; здесь нужны только цифры, 'v', 's' и пробел,
поэтому таблица компактная и читаемая прямо в коде.
"""

# строки по 5 бит (1 = точка), 7 строк сверху вниз
_ROWS = {
    "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
    "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "3": ["11111", "00010", "00100", "00010", "00001", "10001", "01110"],
    "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
    "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
    "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    "v": ["00000", "10001", "10001", "10001", "10001", "01010", "00100"],
    "s": ["00000", "01111", "10000", "01110", "00001", "11110", "00000"],
    "b": ["10000", "10000", "10110", "11001", "10001", "11001", "10110"],
    "o": ["00000", "00000", "01110", "10001", "10001", "10001", "01110"],
    "E": ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "-": ["00000", "00000", "00000", "11111", "00000", "00000", "00000"],
    " ": ["00000", "00000", "00000", "00000", "00000", "00000", "00000"],
}

WIDTH = 5
HEIGHT = 7
SPACING = 1  # пустая колонка между символами


def glyph(ch):
    """Пиксели символа: список (x, y) в координатах 5x7."""
    rows = _ROWS.get(ch) or _ROWS[" "]
    out = []
    for y, row in enumerate(rows):
        for x, bit in enumerate(row):
            if bit == "1":
                out.append((x, y))
    return out


def text_width(text):
    if not text:
        return 0
    return len(text) * (WIDTH + SPACING) - SPACING
